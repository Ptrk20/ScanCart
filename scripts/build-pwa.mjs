import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const corePages = ["/", "/basket", "/scan", "/history", "/products/new", "/shopping/new"];

export function applicationAssets(html) {
  return [...new Set([...html.matchAll(/(?:src|href)="([^"]+)"/g)]
    .map((match) => match[1].replaceAll("&amp;", "&"))
    .filter((url) => url.startsWith("/_next/static/") && !url.includes("?")))];
}

export async function buildPwa(root = process.cwd()) {
  const buildId = (await readFile(path.join(root, ".next", "BUILD_ID"), "utf8")).trim();
  const assets = new Set(["/offline.html", "/manifest.webmanifest", "/icons/icon-192.png", "/icons/icon-512.png", "/icons/maskable-512.png", "/icons/apple-touch-icon.png"]);
  for (const page of corePages) {
    const relative = page === "/" ? "index" : page.slice(1);
    const html = await readFile(path.join(root, ".next", "server", "app", `${relative}.html`), "utf8");
    for (const asset of applicationAssets(html)) assets.add(asset);
  }
  const config = { version: buildId, pages: corePages, assets: [...assets] };
  const source = await readFile(path.join(root, "src", "lib", "pwa", "service-worker.js"), "utf8");
  await writeFile(path.join(root, "public", "sw.js"), `/* Generated by npm run build. Do not edit. */\nconst CONFIG = ${JSON.stringify(config)};\n${source}`);
  console.log(`ScanCart PWA ${buildId}: ${corePages.length} core pages and ${assets.size} assets.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildPwa();
}
