import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const corePages = ["/", "/basket", "/scan", "/history", "/products/new", "/shopping/new"];

export async function buildPwa(root = process.cwd()) {
  const buildId = (await readFile(path.join(root, ".next", "BUILD_ID"), "utf8")).trim();
  const assets = ["/offline.html", "/manifest.webmanifest", "/icons/icon-192.png", "/icons/icon-512.png", "/icons/maskable-512.png", "/icons/apple-touch-icon.png"];
  const config = { version: buildId, pages: corePages, assets };
  const source = await readFile(path.join(root, "src", "lib", "pwa", "service-worker.js"), "utf8");
  await writeFile(path.join(root, "public", "sw.js"), `/* Generated by npm run build. Do not edit. */\nconst CONFIG = ${JSON.stringify(config)};\n${source}`);
  console.log(`ScanCart PWA ${buildId}: ${corePages.length} core pages and ${assets.length} fixed assets; page scripts/styles are discovered during worker installation.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildPwa();
}
